// Downloads the JLPT kanji decks and KanjiVG stroke-order data.
// Usage: node scripts/fetch-data.mjs [--skip-existing]
import { mkdir, writeFile, access } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const LEVELS = ['n5', 'n4', 'n3', 'n2', 'n1']
const DECKS_URL = 'https://www.kanjitest.online/api/decks.json'
const SVG_BASE = 'https://raw.githubusercontent.com/KanjiVG/kanjivg/master/kanji/'
const skipExisting = process.argv.includes('--skip-existing')

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

async function get(url) {
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(url, {
        headers: { 'user-agent': 'kanji-trainer-data-script' },
      })
      if (res.status === 404) return null
      if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`)
      return await res.text()
    } catch (err) {
      if (attempt === 3) throw err
      await sleep(500 * attempt)
    }
  }
  return null
}

async function exists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

async function pool(items, limit, fn) {
  let i = 0
  const workers = Array.from(
    { length: Math.min(limit, items.length) },
    async () => {
      while (i < items.length) {
        const idx = i++
        await fn(items[idx], idx)
      }
    },
  )
  await Promise.all(workers)
}

function normalizeEntry(raw) {
  const arr = (v) => (Array.isArray(v) ? v.filter((s) => typeof s === 'string') : [])
  return {
    kanji: raw.kanji,
    kun: arr(raw.kun),
    on: arr(raw.on),
    meanings: arr(raw.meanings),
    strokes: Number(raw.strokes) || 0,
    examples: (Array.isArray(raw.examples) ? raw.examples : [])
      .slice(0, 4)
      .map((e) => ({
        word: e.word ?? '',
        reading: e.reading ?? '',
        english: e.english ?? '',
        sentence: e.sentence ?? '',
        sentenceEnglish: e.sentenceEnglish ?? '',
      })),
  }
}

async function main() {
  const started = Date.now()

  console.log('Fetching JLPT decks...')
  const rawDecks = JSON.parse(await get(DECKS_URL))

  const decksDir = join(ROOT, 'src', 'data', 'decks')
  await mkdir(decksDir, { recursive: true })
  const totals = {}

  for (const level of LEVELS) {
    const out = join(decksDir, `${level}.ts`)
    if (skipExisting && (await exists(out))) {
      console.log(`  ${level}: skipped (exists)`)
      continue
    }
    const entries = (rawDecks[level] ?? []).map(normalizeEntry)
    totals[level] = entries.length
    const body =
      '// Generated by scripts/fetch-data.mjs — do not edit by hand.\n' +
      "import type { KanjiEntry } from '../../types'\n\n" +
      `export const deck: KanjiEntry[] = ${JSON.stringify(entries)}\n`
    await writeFile(out, body, 'utf8')
    console.log(`  ${level}: ${entries.length} kanji`)
  }

  const metaPath = join(ROOT, 'src', 'data', 'meta.ts')
  if (!(skipExisting && (await exists(metaPath)))) {
    const meta =
      '// Generated by scripts/fetch-data.mjs — do not edit by hand.\n' +
      "import type { Level } from '../types'\n\n" +
      'export const levelTotals: Record<Level, number> = ' +
      JSON.stringify(
        Object.fromEntries(LEVELS.map((l) => [l, (rawDecks[l] ?? []).length])),
      ) +
      '\n'
    await writeFile(metaPath, meta, 'utf8')
  }

  const allKanji = [...new Set(LEVELS.flatMap((l) => (rawDecks[l] ?? []).map((e) => e.kanji)))]
  console.log(`\nFetching KanjiVG stroke data: ${allKanji.length} unique kanji...`)

  const strokesDir = join(ROOT, 'public', 'strokes')
  await mkdir(strokesDir, { recursive: true })

  const missing = []
  let done = 0
  let written = 0

  await pool(allKanji, 8, async (kanji) => {
    const hex = kanji.codePointAt(0).toString(16).padStart(5, '0')
    const out = join(strokesDir, `${hex}.json`)
    if (skipExisting && (await exists(out))) {
      done++
      return
    }
    const svg = await get(`${SVG_BASE}${hex}.svg`)
    done++
    if (svg == null) {
      missing.push(kanji)
      return
    }
    const strokes = [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)].map((m) => m[1])
    if (strokes.length === 0) {
      missing.push(kanji)
      return
    }
    await writeFile(out, JSON.stringify({ strokes }), 'utf8')
    written++
    if (done % 250 === 0) console.log(`  ${done}/${allKanji.length}`)
  })

  console.log(`\nDone in ${((Date.now() - started) / 1000).toFixed(1)}s`)
  console.log(`  stroke files written: ${written}`)
  if (missing.length > 0) {
    console.log(`  no stroke data (${missing.length}): ${missing.join(' ')}`)
  }
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
