export function getListeningLevel(level: 1 | 2 | 3): ListeningLevelData | undefined {
  return listeningN5.find((l) => l.id === level)
}

export function getListeningExercise(level: 1 | 2 | 3, exerciseId: string) {
  const lvl = getListeningLevel(level)
  return lvl?.exercises.find((e) => e.id === exerciseId)
}
